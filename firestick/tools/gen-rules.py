#!/usr/bin/env python3
"""Writes every build's AlgoRules file from shared/rules.json, the one source for algorithm tunables.

    tools/gen-rules.py            write the three files
    tools/gen-rules.py --check    say whether any is out of date, change nothing (exit 1 if so)

Generated rather than read at runtime on purpose: a constant costs nothing to start on a 900 MB stick, a typo is
a build failure instead of a row that quietly empties, and each build keeps compile-time names. The stamp in each
generated file is a hash of the values it was made from, so a file edited by hand, or left behind after an edit
here, is caught by --check rather than by someone noticing two builds behaving differently.

Paths are relative to this repo and its siblings; a build whose folder is missing is skipped with a line saying so.
"""
import hashlib
import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "rules.json"

# Where the other two builds live. Siblings of this repo by default; a checkout somewhere else is named in
# tools/gen-rules.local (untracked, "<build>=<path to the repo root>" per line) or in DREAM_WINDOWS_DIR /
# DREAM_IOS_DIR. No one's folder layout is written into this file: it is published with the rest of the code.
def repo(build, env, default):
    local = ROOT / "tools" / "gen-rules.local"
    if local.exists():
        for line in local.read_text(encoding="utf-8").splitlines():
            name, _, path = line.partition("=")
            if name.strip().lower() == build.lower() and path.strip():
                return pathlib.Path(path.strip()).expanduser()
    return pathlib.Path(os.environ.get(env, "")).expanduser() if os.environ.get(env) else default


TARGETS = {
    "Fire Stick": ROOT / "app/src/main/java/com/firehome/launcher/AlgoRules.kt",
    "Windows": repo("windows", "DREAM_WINDOWS_DIR", ROOT.parent / "dream-os-windows")
        / "core/src/main/kotlin/com/dreamos/desktop/core/content/AlgoRules.kt",
    "iPhone": repo("ios", "DREAM_IOS_DIR", ROOT.parent / "DreamOS-iOS")
        / "app/Sources/DreamContent/AlgoRules.swift",
}

HEADER = (
    "Every tunable of the discovery and ranking algorithm, for all three builds.\n"
    "\n"
    "GENERATED from fire-home/shared/rules.json by tools/gen-rules.py. Do not edit this file: edit the JSON and run\n"
    "the generator, or the next run overwrites what you wrote and `--check` fails. One edit, three builds, which is\n"
    "the whole point of it living in one place.\n"
    "\n"
    "Change a value only with the harness open (fire-home app/src/test, AlgoHarnessTest): it ranks the same rows\n"
    "before and after, and the numbers belong in the commit message."
)


def camel(name):
    """W_ORDER -> wOrder, FRESH_1Y -> fresh1Y."""
    head, *rest = name.lower().split("_")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def digest(data):
    flat = [(v["name"], v["type"], v["value"]) for s in data["sections"] for v in s["values"]]
    return hashlib.sha256(json.dumps(flat, sort_keys=True).encode()).hexdigest()[:16]


def literal(v, kind, lang):
    if kind == "double":
        return repr(float(v))
    if kind == "long":
        return f"{v}L" if lang == "kotlin" else str(v)
    return str(v)


def wrap(text, width, prefix):
    """Doc text as comment lines, broken on words so a long sentence does not run off the screen."""
    out, line = [], prefix.rstrip()
    for word in text.split():
        candidate = f"{line} {word}" if line.strip() != prefix.strip() else f"{prefix}{word}"
        if len(candidate) > width and line.strip() != prefix.strip():
            out.append(line)
            line = f"{prefix}{word}"
        else:
            line = candidate
    out.append(line)
    return out


def kotlin(data, package, stamp):
    lines = [f"package {package}", ""]
    lines += ["/**"] + [f" * {l}".rstrip() for l in HEADER.split("\n")] + [" *", f" * Source stamp: {stamp}", " */"]
    lines += ["object AlgoRules {"]
    for i, section in enumerate(data["sections"]):
        lines.append(("" if i == 0 else "\n") + f"    // ---- {section['title']} ----\n")
        for v in section["values"]:
            if v.get("doc"):
                doc = wrap(v["doc"], 118, "     * ")
                lines += ["    /**"] + doc + ["     */"] if len(doc) > 1 else [f"    /** {v['doc']} */"]
            lines.append(f"    const val {v['name']} = {literal(v['value'], v['type'], 'kotlin')}")
    lines += ["}", ""]
    return "\n".join(lines)


def swift(data, stamp):
    lines = ["import Foundation", ""]
    lines += [f"/// {l}".rstrip() for l in HEADER.split("\n")] + ["///", f"/// Source stamp: {stamp}"]
    lines += ["public enum AlgoRules {"]
    for i, section in enumerate(data["sections"]):
        lines.append(("" if i == 0 else "\n") + f"    // MARK: {section['title']}\n")
        for v in section["values"]:
            if v.get("doc"):
                lines += wrap(v["doc"], 118, "    /// ")
            kind = {"double": "Double", "int": "Int", "long": "Int64"}[v["type"]]
            lines.append(f"    public static let {camel(v['name'])}: {kind} = {literal(v['value'], v['type'], 'swift')}")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    names = [v["name"] for s in data["sections"] for v in s["values"]]
    if len(names) != len(set(names)):
        sys.exit(f"gen-rules: two values share a name: {sorted(n for n in names if names.count(n) > 1)}")
    stamp = digest(data)
    check = "--check" in sys.argv
    stale = []
    for build, path in TARGETS.items():
        if not path.parent.exists():
            print(f"  {build}: no folder at {path.parent}, skipped")
            continue
        want = swift(data, stamp) if path.suffix == ".swift" else kotlin(data, path_package(path), stamp)
        have = path.read_text(encoding="utf-8") if path.exists() else ""
        if have == want:
            print(f"  {build}: up to date")
            continue
        stale.append(build)
        if check:
            print(f"  {build}: OUT OF DATE ({path})")
        else:
            path.write_text(want, encoding="utf-8", newline="\n")
            print(f"  {build}: written ({len(names)} values) -> {path}")
    if check and stale:
        sys.exit(f"gen-rules: out of date: {', '.join(stale)}. Run tools/gen-rules.py.")
    print(f"gen-rules: {len(names)} values, stamp {stamp}")


def path_package(path):
    """The Kotlin package from the file's own folder, so a moved file does not need the generator edited."""
    parts = path.resolve().parts
    for anchor in ("java", "kotlin"):
        if anchor in parts:
            return ".".join(parts[parts.index(anchor) + 1:-1])
    sys.exit(f"gen-rules: cannot tell the package for {path}")


if __name__ == "__main__":
    main()
